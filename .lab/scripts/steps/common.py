"""Shared checks for step scorers."""

from __future__ import annotations

from typing import List, Optional, Tuple

import re
import textwrap


def new_files(ev, prefix: str, suffix: str = "") -> List[str]:
    """Files under prefix that did not exist at the setup commit."""
    existing = set(ev.git("ls-tree", "-r", "--name-only", ev.meta["base"]).split())
    return [f for f in ev.changed() if f.startswith(prefix) and f.endswith(suffix) and f not in existing]


def touched(ev, prefix: str) -> List[str]:
    return [f for f in ev.changed() if f.startswith(prefix)]


def final_message(ev) -> str:
    """The agent's last reply in the --share transcript (text after the last '### Copilot')."""
    t = ev.transcript
    i = t.rfind("\n### Copilot")
    if i < 0:
        return t[-4000:]
    body = t[i + len("\n### Copilot"):]
    return body.split("<sub>Generated by")[0]


EDIT_TOOLS = {"apply_patch", "edit", "create", "write", "str_replace", "str_replace_editor", "insert"}


def calls(ev) -> List[Tuple[int, str, str]]:
    """Tool calls in transcript order: (position, tool name, section text)."""
    out = []
    for m in re.finditer(r"\n### `([^`]+)`", ev.transcript):
        end = ev.transcript.find("\n### ", m.end())
        out.append((m.start(), m.group(1), ev.transcript[m.end(): end if end > 0 else None]))
    return out


def first_edit(ev, path_part: str) -> Optional[int]:
    """Position of the first edit to a file whose path contains path_part (edit tools or sed -i)."""
    for pos, name, body in calls(ev):
        if "Denied by preToolUse hook" in body or "Denied, no one to approve" in body:
            continue  # the hook stopped it: nothing changed
        if name in EDIT_TOOLS and path_part in body:
            return pos
        if name in {"bash", "shell", "powershell"} and path_part in body and re.search(r"sed -i|> *\S*" + re.escape(path_part) + r"|perl -pi|python3? -c|Set-Content|Out-File|WriteAllText", body):
            return pos
    return None


def first_call(ev, pred) -> Optional[int]:
    for pos, name, body in calls(ev):
        if pred(name, body):
            return pos
    return None
