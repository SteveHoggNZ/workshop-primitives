"""Shared checks for step scorers."""

from __future__ import annotations

from typing import List, Optional, Tuple

import re
import textwrap


def new_files(ev, prefix: str, suffix: str = "") -> List[str]:
    """Files under prefix that did not exist at the setup commit."""
    existing = set(ev.git("ls-tree", "-r", "--name-only", ev.meta["base"]).split())
    return [f for f in ev.changed() if f.startswith(prefix) and f.endswith(suffix) and f not in existing]


def touched(ev, prefix: str) -> List[str]:
    return [f for f in ev.changed() if f.startswith(prefix)]


def final_message(ev) -> str:
    """The agent's last reply in the --share transcript (text after the last '### Copilot')."""
    t = ev.transcript
    i = t.rfind("\n### Copilot")
    if i < 0:
        return t[-4000:]
    body = t[i + len("\n### Copilot"):]
    return body.split("<sub>Generated by")[0]


EDIT_TOOLS = {"apply_patch", "edit", "create", "write", "str_replace", "str_replace_editor", "insert"}


def calls(ev) -> List[Tuple[int, str, str]]:
    """Tool calls in transcript order: (position, tool name, section text)."""
    out = []
    for m in re.finditer(r"(?:\A|\n)### `([^`]+)`", ev.transcript):
        end = ev.transcript.find("\n### ", m.end())
        out.append((m.start(), m.group(1), ev.transcript[m.end(): end if end > 0 else None]))
    return out


def _command(body: str) -> str:
    """The command line of a shell call (the `$ ...` line), not its output."""
    m = re.search(r"`\$ ([^`]*)`", body)
    return m.group(1) if m else ""


def first_edit(ev, path_part: str) -> Optional[int]:
    """Position of the first edit to a file whose path contains path_part (edit tools, or a shell command
    that writes: sed -i, a redirect, PowerShell Set-Content ...). Only a shell call's command line is read,
    not its output: `dotnet test` prints `Tasks.App -> .../src/Tasks.App/bin/...`, which isn't an edit
    (Step 4 review). Backslash paths count the same as forward-slash ones."""
    part = path_part.replace("\\", "/")
    for pos, name, body in calls(ev):
        if "Denied by preToolUse hook" in body or "Denied, no one to approve" in body:
            continue  # the hook stopped it: nothing changed
        if name in EDIT_TOOLS and part in body.replace("\\\\", "/").replace("\\", "/"):
            return pos
        if name in {"bash", "shell", "powershell"}:
            cmd = _command(body).replace("\\", "/")
            if part in cmd and re.search(r"sed -i|>>? *\S*" + re.escape(part) + r"|perl -pi|python3? -c|Set-Content|Add-Content|Out-File|WriteAllText|\btee\b|\bmv\b|\bcp\b", cmd):
                return pos
    return None


def first_call(ev, pred) -> Optional[int]:
    for pos, name, body in calls(ev):
        if pred(name, body):
            return pos
    return None


SHELLS = {"bash", "shell", "powershell"}
SHELL_READS = {"read_bash", "read_powershell", "write_bash", "write_powershell"}


def shell_runs(ev) -> List[Tuple[int, str, str]]:
    """Shell commands in transcript order: (position, command line, output).

    A long command can return before it finishes; its output then arrives in later read_bash calls
    (found in Step 4: `./lab tdd green` printed GREEN in a read_bash). Those outputs are joined to the
    command they belong to, so a check can look at the command and its output together."""
    out: List[List] = []
    for pos, name, body in calls(ev):
        if name in SHELLS:
            m = re.search(r"`\$ ([^`]*)`", body)
            out.append([pos, m.group(1) if m else body[:200], body])
        elif name in SHELL_READS and out:
            out[-1][2] += "\n" + body
    return [tuple(x) for x in out]
